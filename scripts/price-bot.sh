#!/usr/bin/env bash
# The price-update bot (.github/workflows/update-prices.yml): keeps exactly one PR open from branch
# bot/update-prices against the ref the workflow ran on, current with models.dev.
#
#   price-bot.sh run       regenerate, then open / update / close the PR (writes outcome to $GITHUB_OUTPUT)
#   price-bot.sh report    open or update the single `prices` issue about a failure (reads FAILURE, DETAIL)
#
# Environment: GH_REPO (owner/repo), BASE (branch the PR targets), BOT_TOKEN (PRICES_BOT_TOKEN: push and PR,
# so CI runs on the PR), GITHUB_TOKEN (issues and run history only), RUN_URL, RUNNER_TEMP.
set -euo pipefail

BRANCH=bot/update-prices
TITLE="chore(prices): update model price table"
ISSUE_TITLE="Price table update is failing"
LABEL=prices
TMP=${RUNNER_TEMP:-$(mktemp -d)}

out() { if [[ -n "${GITHUB_OUTPUT:-}" ]]; then echo "$1=$2" >>"$GITHUB_OUTPUT"; fi; echo "$1=$2"; }
bot_gh() { GH_TOKEN=$BOT_TOKEN gh "$@"; }

check_token() {
  # A fine-grained PAT that expired or was revoked fails here, before anything else uses it.
  if ! bot_gh api "repos/$GH_REPO" --jq .full_name >/dev/null 2>"$TMP/token.err"; then
    echo "::error::PRICES_BOT_TOKEN expired or invalid: renew it (see docs/development.md, Price table bot)."
    out failure token
    out detail "PRICES_BOT_TOKEN expired or invalid: renew it (see docs/development.md). gh said: $(head -c 300 "$TMP/token.err" | tr '\n' ' ')"
    exit 1
  fi
}

open_pr() { bot_gh pr list --head "$BRANCH" --base "$BASE" --state open --json number --jq '.[0].number // empty'; }

delete_branch() {
  # Another open PR from the same branch (against another base) still needs it.
  if [[ -n "$(bot_gh pr list --head "$BRANCH" --state open --json number --jq '.[0].number // empty')" ]]; then
    echo "$BRANCH is still used by another open PR; not deleting it."
    return
  fi
  if git ls-remote --exit-code --heads origin "$BRANCH" >/dev/null 2>&1; then
    bot_gh api -X DELETE "repos/$GH_REPO/git/refs/heads/$BRANCH" >/dev/null
    echo "Deleted $BRANCH."
  fi
}

run() {
  check_token
  set +e
  npm run --silent update:prices -- --json "$TMP/prices.json" 2>&1 | tee "$TMP/update.log"
  local code=${PIPESTATUS[0]}
  set -e
  if [[ $code -ne 0 ]]; then
    out failure "$([[ $code -eq 3 ]] && echo fetch || echo generator)"
    out detail "update:prices exited $code: $(grep -m1 'update-prices failed' "$TMP/update.log" | head -c 500)"
    exit 1
  fi

  local pr
  pr=$(open_pr)
  if git diff --quiet -- src/pricing-data.ts; then
    echo "$BASE already has the current prices."
    if [[ -n "$pr" ]]; then
      bot_gh pr close "$pr" --comment "Closing: \`$BASE\` already matches models.dev ($RUN_URL)."
      echo "Closed #$pr."
    fi
    delete_branch
    out outcome up-to-date
    return
  fi

  # Typecheck and tests on the new table; a failure still opens the PR, marked failing, so it is seen.
  local tests=pass
  { npm run --silent typecheck && npm run --silent build && npm test --silent; } >"$TMP/tests.log" 2>&1 || tests=fail
  if [[ $tests == fail ]]; then
    echo "::warning::Typecheck or tests fail with the new price table; see the PR."
    tail -n 40 "$TMP/tests.log"
  fi

  npx tsx scripts/price-pr-body.ts "$TMP/prices.json" --tests "$tests" --run-url "$RUN_URL" --base "$BASE" >"$TMP/body.md"

  git config user.name "github-actions[bot]"
  git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
  git switch -q -C "$BRANCH"
  git add src/pricing-data.ts
  git commit -q -m "$TITLE" -m "Generated by .github/workflows/update-prices.yml ($RUN_URL)."
  # Push only when the content changed, so an unchanged PR is not re-run for nothing.
  local remote_tree=""
  if git fetch -q origin "$BRANCH" 2>/dev/null; then remote_tree=$(git rev-parse "FETCH_HEAD^{tree}"); fi
  if [[ "$remote_tree" != "$(git rev-parse 'HEAD^{tree}')" || -z "$pr" ]]; then
    local auth
    auth=$(printf 'x-access-token:%s' "$BOT_TOKEN" | base64 -w0)
    echo "::add-mask::$auth"
    git -c "http.https://github.com/.extraheader=AUTHORIZATION: basic $auth" push -q --force origin "HEAD:refs/heads/$BRANCH"
  fi

  if [[ -n "$pr" ]]; then
    bot_gh pr edit "$pr" --title "$TITLE" --body-file "$TMP/body.md" >/dev/null
    echo "Updated #$pr."
    out outcome updated
  else
    bot_gh pr create --base "$BASE" --head "$BRANCH" --title "$TITLE" --body-file "$TMP/body.md"
    out outcome opened
  fi
  out tests "$tests"
}

report() {
  # GITHUB_TOKEN, not the PAT: the PAT may be the thing that failed.
  local kind=${FAILURE:-unknown} detail=${DETAIL:-"see the run log"}
  if [[ $kind == fetch ]]; then
    # One failed fetch is usually a blip; report only when the previous run of this workflow failed too.
    local prev
    prev=$(gh run list --workflow update-prices.yml --branch "$BASE" --status completed --limit 1 --json conclusion --jq '.[0].conclusion // empty')
    if [[ "$prev" != failure ]]; then
      echo "Fetch failed once (previous run: ${prev:-none}); not opening an issue yet."
      return
    fi
  fi
  local label=(--label "$LABEL")
  if ! gh api "repos/$GH_REPO/labels/$LABEL" >/dev/null 2>&1 &&
    ! gh label create "$LABEL" --color FBCA04 --description "Model price table and its update bot" >/dev/null 2>&1; then
    label=()
  fi
  local body="The price update failed on \`$BASE\` ($kind): $detail

Run: $RUN_URL

Fix the cause (or renew \`PRICES_BOT_TOKEN\`), then re-run the workflow from the Actions tab. Close this issue once a run passes."
  local issue
  # The issue list, not search: search is indexed with a delay, and two quick failures must find the same issue.
  issue=$(gh issue list --state open --limit 200 --json number,title --jq "[.[] | select(.title == \"$ISSUE_TITLE\")][0].number // empty")
  if [[ -n "$issue" ]]; then
    gh issue comment "$issue" --body "$body" >/dev/null
    echo "Commented on #$issue."
  else
    gh issue create --title "$ISSUE_TITLE" "${label[@]}" --body "$body"
  fi
}

"${1:?usage: price-bot.sh run|report}"
