import type { Rng } from "./random.js";
import type { Block, Item, SessionScript, ToolCall } from "./script.js";
import { TokenModel, costOf } from "./tokens.js";

type Json = Record<string, unknown>;

/** A 1×1 PNG, small enough to embed. */
export const TINY_PNG = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==";

/** Priced in src/pricing-data.ts, so fixture sessions show an estimated cost. */
export const CLAUDE_FIXTURE_MODEL = "claude-opus-5-5";
const MODEL = CLAUDE_FIXTURE_MODEL;

/** Emit a Claude Code transcript (`~/.claude/projects/<slug>/<id>.jsonl`) for a script. */
export function emitClaudeCode(script: SessionScript, rng: Rng, opts: { sessionId: string; start: number; home: string; username: string }): string {
  const lines: Json[] = [];
  const tokens = new TokenModel(rng, "anthropic");
  let last: string | null = null;
  let now = opts.start;
  let branch = "main";
  let totalCost = 0;
  let lastPrompt = "";

  const tick = (min: number, max: number) => {
    now += rng.int(min, max) * 1000;
    return new Date(now).toISOString();
  };
  const entry = (type: string, extra: Json, parent: string | null = last): Json => {
    const uuid = rng.uuid();
    const e: Json = {
      parentUuid: parent,
      isSidechain: false,
      userType: "external",
      cwd: script.cwd,
      sessionId: opts.sessionId,
      version: "2.1.281",
      gitBranch: branch,
      type,
      ...extra,
      uuid,
      timestamp: tick(1, 4),
    };
    lines.push(e);
    last = uuid;
    return e;
  };
  const user = (content: unknown, extra: Json = {}) => entry("user", { message: { role: "user", content }, ...extra });

  lines.push({ type: "permission-mode", permissionMode: "default", sessionId: opts.sessionId });
  lines.push({ type: "file-history-snapshot", messageId: rng.uuid(), snapshot: { trackedFileBackups: {} }, isSnapshotUpdate: false });
  entry("attachment", { attachment: { type: "environment", content: `Working directory: ${script.cwd}\nPlatform: linux\nUser: ${opts.username}` } });
  entry("attachment", { attachment: { type: "instructions", content: `Contents of ${script.cwd}/CLAUDE.md:\n\n# acme-billing-api\n- Use vitest; run \`npm test\` before committing.` } });
  entry("attachment", { attachment: { type: "credential_org", org: "Acme Billing (team plan)" } });

  const emitTools = (calls: { id: string; block: Block }[]) => {
    for (const { id, block } of calls) {
      if (block.k === "subagent") {
        const u = block.call.usage;
        user([{ type: "tool_result", tool_use_id: id, content: [{ type: "text", text: block.call.output }] }], {
          toolUseResult: { status: "completed", agentId: rng.hex(16), totalTokens: u.input + u.output + u.cacheRead, totalToolUseCount: u.toolUses, totalDurationMs: u.durationMs },
        });
        tokens.add(block.call.output.length);
      } else if (block.k === "tool") {
        const c = block.call;
        const content = c.image
          ? [{ type: "text", text: c.output }, { type: "image", source: { type: "base64", media_type: "image/png", data: TINY_PNG } }]
          : c.output;
        user([{ type: "tool_result", tool_use_id: id, content, ...(c.isError ? { is_error: true } : {}) }]);
        tokens.add(c.output.length);
      }
    }
  };

  const emit = (items: Item[]) => {
    for (const item of items) {
      switch (item.t) {
        case "prompt": {
          tick(20, 120);
          const parts: Json[] = [{ type: "text", text: item.text }];
          if (item.reminder) parts.push({ type: "text", text: `<system-reminder>\nThe user's email is ${opts.username}@example-corp.dev. Today's date is 2026-03-10.\n</system-reminder>` });
          if (item.image) parts.push({ type: "image", source: { type: "base64", media_type: "image/png", data: TINY_PNG } });
          user(parts.length === 1 ? item.text : parts);
          tokens.add(item.text.length);
          lastPrompt = item.text;
          break;
        }
        case "command":
          user("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", { isMeta: true });
          user(`<command-name>${item.name}</command-name>\n            <command-message>${item.name.slice(1)}</command-message>\n            <command-args></command-args>`);
          user(`<local-command-stdout>${item.stdout}</local-command-stdout>`);
          break;
        case "commandPrompt":
          user(`<command-name>${item.name}</command-name>\n            <command-message>${item.name.slice(1)}</command-message>\n            <command-args>${item.args ?? ""}</command-args>`);
          user(item.expanded, { isMeta: true });
          tokens.add(item.expanded.length);
          break;
        case "skill": {
          const id = `toolu_${rng.token(24)}`;
          const usage = tokens.respond(40, 0);
          totalCost += costOf(usage);
          entry("assistant", { message: assistantMessage([{ type: "tool_use", id, name: "Skill", input: { skill: item.name } }], usage, `msg_${rng.token(24)}`), requestId: `req_${rng.token(24)}` });
          user([{ type: "tool_result", tool_use_id: id, content: `Launching skill: ${item.name}` }]);
          user(`Base directory for this skill: ${opts.home}/.claude/skills/${item.name}\n\n# ${item.name}\n\nReview checklist: correctness, edge cases, tests.`, { isMeta: true });
          break;
        }
        case "response": {
          const blocks = item.blocks.filter((b) => !(b.k === "tool" && b.call.only === "pi") && b.k !== "subagentList");
          if (!blocks.length) break;
          tick(3, 40);
          const msgId = `msg_${rng.token(24)}`;
          const requestId = `req_${rng.token(24)}`;
          const content = blocks.map((b) => toContent(b, rng));
          const outChars = JSON.stringify(content).length;
          const reasoning = blocks.reduce((n, b) => n + (b.k === "thinking" ? b.tokens : 0), 0);
          const usage = tokens.respond(outChars, reasoning);
          totalCost += costOf(usage);
          for (const c of content) entry("assistant", { message: assistantMessage([c.block], usage, msgId), requestId });
          tick(1, 20);
          emitTools(content.filter((c) => c.toolId).map((c) => ({ id: c.toolId!, block: c.source })));
          break;
        }
        case "interrupt":
          user("[Request interrupted by user]");
          break;
        case "apiError":
          entry("assistant", { isApiErrorMessage: true, message: { id: rng.uuid(), model: "<synthetic>", role: "assistant", type: "message", content: [{ type: "text", text: item.text }], usage: { input_tokens: 0, output_tokens: 0 } } });
          break;
        case "compaction": {
          const pre = tokens.contextTokens;
          const boundary = entry("system", { subtype: "compact_boundary", content: "Conversation compacted", compactMetadata: { trigger: "auto", preTokens: pre }, logicalParentUuid: last }, null);
          last = boundary.uuid as string;
          user(item.summary, { isCompactSummary: true });
          tokens.compact();
          break;
        }
        case "idle":
          now += item.minutes * 60_000;
          tokens.expireCache();
          break;
        case "queuedPrompt":
          entry("attachment", { attachment: { type: "queued_command", commandMode: "prompt", prompt: item.text } });
          tokens.add(item.text.length);
          break;
        case "subagentNotice":
          entry("attachment", { attachment: { type: "queued_command", commandMode: "task-notification", prompt: `<task-notification>${item.text}</task-notification>` } });
          break;
        case "abandoned": {
          const fork = last;
          emit(item.items);
          last = fork;
          break;
        }
        case "modelChange":
        case "thinkingLevel":
          break; // Claude Code records these via /model and settings, not transcript entries.
      }
      if (item.t === "response" && item.blocks.some((b) => b.k === "tool" && b.call.command?.startsWith("git checkout -b"))) {
        branch = /git checkout -b (\S+)/.exec(item.blocks.map((b) => (b.k === "tool" ? b.call.command ?? "" : "")).join(" "))?.[1] ?? branch;
      }
    }
  };
  emit(script.items);

  lines.push({ type: "ai-title", aiTitle: script.title, sessionId: opts.sessionId });
  lines.push({ type: "last-prompt", lastPrompt, sessionId: opts.sessionId });
  lines.push({ type: "cost-state", sessionId: opts.sessionId, totalCostUSD: Number(totalCost.toFixed(4)), totalDuration: now - opts.start });
  return `${lines.map((l) => JSON.stringify(l)).join("\n")}\n`;
}

function assistantMessage(content: unknown[], usage: ReturnType<TokenModel["respond"]>, id: string): Json {
  return {
    id,
    model: MODEL,
    role: "assistant",
    type: "message",
    content,
    stop_reason: null,
    usage: {
      input_tokens: usage.input,
      cache_creation_input_tokens: usage.cacheWrite,
      // Subscription Claude Code writes 1-hour cache entries.
      cache_creation: { ephemeral_5m_input_tokens: 0, ephemeral_1h_input_tokens: usage.cacheWrite },
      cache_read_input_tokens: usage.cacheRead,
      output_tokens: usage.output,
      ...(usage.reasoning ? { output_tokens_details: { thinking_tokens: usage.reasoning } } : {}),
      service_tier: "standard",
    },
  };
}

function toContent(b: Block, rng: Rng): { block: Json; toolId?: string; source: Block } {
  if (b.k === "thinking") return { block: { type: "thinking", thinking: "", signature: rng.token(120) }, source: b };
  if (b.k === "text") return { block: { type: "text", text: b.text }, source: b };
  const id = `toolu_${rng.token(24)}`;
  if (b.k === "subagent") {
    return { block: { type: "tool_use", id, name: "Agent", input: { subagent_type: b.call.agents[0], description: b.call.description, prompt: b.call.prompt } }, toolId: id, source: b };
  }
  if (b.k !== "tool") throw new Error("unreachable");
  const [name, input] = claudeTool(b.call);
  return { block: { type: "tool_use", id, name, input }, toolId: id, source: b };
}

function claudeTool(c: ToolCall): [string, Json] {
  switch (c.kind) {
    case "read":
      return ["Read", { file_path: c.path }];
    case "edit":
      return ["Edit", { file_path: c.path, old_string: c.oldText, new_string: c.newText }];
    case "write":
      return ["Write", { file_path: c.path, content: c.content }];
    case "bash":
      return ["Bash", { command: c.command, description: c.command?.split(" ").slice(0, 3).join(" ") }];
    case "grep":
      return ["Grep", { pattern: c.pattern, path: c.path, output_mode: "content" }];
    case "glob":
      return ["Glob", { pattern: c.pattern }];
    case "web":
      return ["WebFetch", { url: c.url, prompt: "Summarise the relevant section" }];
    case "todo":
      return ["TodoWrite", { todos: JSON.parse(c.content ?? "[]") }];
    case "mcp":
      return ["mcp__linear__get_issue", { id: "BILL-ticket" }];
  }
}
