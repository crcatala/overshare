import { describe, expect, it } from "vitest";
import { parseClaudeCode } from "../src/adapters/claude-code.js";
import { detectHarness } from "../src/adapters/index.js";
import { computeStats } from "../src/stats.js";
import { ClaudeTranscript, ccUsage } from "./helpers.js";

describe("claude-code adapter", () => {
  it("counts usage once per API response even though each block is its own line", () => {
    const t = new ClaudeTranscript()
      .user("fix the bug")
      .assistant(
        "msg_1",
        [
          { type: "thinking", thinking: "", signature: "sig" },
          { type: "text", text: "Looking." },
          { type: "tool_use", id: "tu_1", name: "Bash", input: { command: "git status\ngit diff" } },
        ],
        ccUsage(10, 50, 1000, 200, 30),
      )
      .toolResult("tu_1", "clean")
      .assistant("msg_2", [{ type: "text", text: "Done." }], ccUsage(5, 20, 1200, 0));
    const { session } = parseClaudeCode(t.toJsonl());
    expect(session.responses).toHaveLength(2);
    expect(session.responses[0]!.usage).toEqual({ input: 10, output: 50, cacheRead: 1000, cacheWrite: 200, reasoning: 30 });
    const stats = computeStats(session);
    expect(stats.tokens.output).toBe(70);
    expect(stats.peakContext).toBe(1210);
    expect(stats.thinking).toEqual({ blocks: 1, chars: 0, tokens: 30 });

    const steps = session.turns[0]!.steps;
    expect(steps.map((s) => s.kind)).toEqual(["thinking", "text", "tool", "text"]);
    const tool = steps[2]!;
    expect(tool.kind === "tool" && tool.summary).toBe("git status");
    expect(tool.kind === "tool" && tool.result?.text).toBe("clean");
    expect(steps[0]!.kind === "thinking" && steps[0]!.tokens).toBe(30);
  });

  it("drops injected context: attachments, meta caveats and system reminders", () => {
    const t = new ClaudeTranscript()
      .attachment({ type: "environment", content: "user email is someone@corp.test" })
      .attachment({ type: "credential_org", org: "secret org" })
      .user("<local-command-caveat>Caveat: generated by local commands</local-command-caveat>", { isMeta: true })
      .user("hello<system-reminder>internal context</system-reminder>")
      .assistant("m1", [{ type: "text", text: "hi" }], ccUsage(1, 1));
    const { session, dropped } = parseClaudeCode(t.toJsonl());
    expect(session.turns).toHaveLength(1);
    expect(session.turns[0]!.user?.text).toBe("hello");
    expect(JSON.stringify(session)).not.toContain("internal context");
    expect(JSON.stringify(session)).not.toContain("secret org");
    expect(dropped["attachment:environment"]).toBe(1);
    expect(dropped["attachment:credential_org"]).toBe(1);
  });

  it("turns local commands into events and prompt-expanding commands into turns", () => {
    const t = new ClaudeTranscript()
      .user("<command-name>/effort</command-name>\n<command-message>effort</command-message>\n<command-args></command-args>")
      .user("<local-command-stdout>Set effort level to high</local-command-stdout>")
      .user("<command-name>/workflow:review</command-name>\n<command-args>PR 12</command-args>")
      .user("Review the PR carefully.", { isMeta: true })
      .assistant("m1", [{ type: "text", text: "Reviewing" }], ccUsage(1, 1));
    const { session } = parseClaudeCode(t.toJsonl());
    const [turn0, turn1] = session.turns;
    expect(turn0!.user).toBeUndefined();
    expect(turn0!.steps[0]).toMatchObject({ kind: "event", event: "command", text: "/effort", detail: "Set effort level to high" });
    expect(turn1!.user).toMatchObject({ text: "/workflow:review PR 12", command: { name: "/workflow:review", args: "PR 12" }, expanded: "Review the PR carefully." });
  });

  it("records skills, interruptions, synthetic errors and compaction", () => {
    const t = new ClaudeTranscript()
      .user("<command-name>/agent-browser</command-name>")
      .user("Base directory for this skill: /home/tester/.claude/skills/agent-browser\n# docs", { isMeta: true })
      .assistant("m1", [{ type: "text", text: "ok" }], ccUsage(1, 1))
      .user("[Request interrupted by user]")
      .assistant("m2", [{ type: "text", text: "API Error: overloaded" }], ccUsage(0, 0), "<synthetic>")
      .system("compact_boundary", { compactMetadata: { preTokens: 150000 } });
    const { session } = parseClaudeCode(t.toJsonl());
    const events = session.turns.flatMap((x) => x.steps).filter((s) => s.kind === "event");
    expect(events.map((e) => e.kind === "event" && e.event)).toEqual(["skill", "interrupted", "interrupted", "compaction"]);
    expect(session.models).toEqual(["claude-test-1"]);
    expect(session.responses).toHaveLength(1);
  });

  it("follows the latest branch after a rewind", () => {
    const t = new ClaudeTranscript().user("first").assistant("m1", [{ type: "text", text: "a1" }], ccUsage(1, 1));
    const fork = t.lastUuid;
    t.user("abandoned prompt").assistant("m2", [{ type: "text", text: "a2" }], ccUsage(1, 1));
    t.rewindTo(fork).user("edited prompt").assistant("m3", [{ type: "text", text: "a3" }], ccUsage(1, 1));
    const { session } = parseClaudeCode(t.toJsonl());
    expect(session.turns.map((x) => x.user?.text)).toEqual(["first", "edited prompt"]);
  });

  it("treats queued prompts as turns but drops task notifications", () => {
    const t = new ClaudeTranscript()
      .user("start")
      .attachment({ type: "queued_command", commandMode: "task-notification", prompt: "<task-notification>x</task-notification>" })
      .attachment({ type: "queued_command", commandMode: "prompt", prompt: "also do this" });
    const { session } = parseClaudeCode(t.toJsonl());
    expect(session.turns.map((x) => x.user?.text)).toEqual(["start", "also do this"]);
  });

  it("detects subagent launches and keeps only metadata-level stats", () => {
    const t = new ClaudeTranscript()
      .user("research this")
      .assistant(
        "m1",
        [{ type: "tool_use", id: "tu_a", name: "Agent", input: { subagent_type: "Explore", description: "Find config loaders", prompt: "long prompt" } }],
        ccUsage(1, 1),
      )
      .toolResult("tu_a", [{ type: "text", text: "Found 3 loaders" }], { toolUseResult: { totalTokens: 12345, totalToolUseCount: 7, totalDurationMs: 9000 } });
    const { session } = parseClaudeCode(t.toJsonl());
    const step = session.turns[0]!.steps[0]!;
    expect(step).toMatchObject({
      kind: "subagent",
      tool: "Agent",
      agents: ["Explore"],
      description: "Find config loaders",
      usage: { totalTokens: 12345, toolUses: 7, durationMs: 9000 },
    });
    expect(computeStats(session).subagents).toBe(1);
  });

  it("reads metadata: title, version, branch, cwd, session cost", () => {
    const t = new ClaudeTranscript()
      .user("hi")
      .meta("ai-title", { aiTitle: "A title" })
      .meta("cost-state", { totalCostUSD: 1.25 });
    const { session } = parseClaudeCode(t.toJsonl());
    expect(session).toMatchObject({
      title: "A title",
      harness: { name: "claude-code", version: "2.1.0" },
      project: { cwd: "/home/tester/work/demo", name: "demo", branch: "main" },
      stats: { cost: 1.25, costSource: "session-total" },
    });
    expect(detectHarness(t.toJsonl())).toBe("claude-code");
  });

  it("counts images and tolerates a torn final line", () => {
    const t = new ClaudeTranscript().user([
      { type: "text", text: "see screenshot" },
      { type: "image", source: { type: "base64", data: "AAAA" } },
    ]);
    const { session } = parseClaudeCode(`${t.toJsonl()}{"type":"assist`);
    expect(session.turns[0]!.user).toEqual({ text: "see screenshot", images: 1 });
    expect(JSON.stringify(session)).not.toContain("AAAA");
  });
});
